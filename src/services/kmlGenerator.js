import { displayNumber, resolveRange } from './towers.js'
import { haversineM } from './geo.js'

export function calcLength(towers) {
  let total = 0
  for (let i = 1; i < towers.length; i++) {
    total += haversineM(towers[i - 1].lat, towers[i - 1].lon, towers[i].lat, towers[i].lon)
  }
  return total
}

export function formatLength(meters) {
  return meters >= 1000
    ? `${(meters / 1000).toFixed(2)} km`
    : `${Math.round(meters)} m`
}

// The towers an export covers, in export order, each stamped with the number it
// should carry. With no START/END picked this is the whole line.
export function selectTowers(towers, fromIdx, toIdx, startNumber = 1) {
  const range = resolveRange(towers, fromIdx, toIdx)
  const picked = []
  for (let i = range.lo; i <= range.hi && i < towers.length; i++) {
    picked.push({ ...towers[i], towerNumber: displayNumber(towers[i], i, range, startNumber) })
  }
  // START after END means the user selected the line backwards — walk it that way.
  return range.explicit && fromIdx > toIdx ? picked.reverse() : picked
}

// Numbers and line names are free-form user text and OSM data; both can carry
// characters that would otherwise break the document.
const xml = (v) =>
  String(v ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')

export function generateKML(towers, fromIdx, toIdx, lineName, startNumber = 1) {
  const selected = selectTowers(towers, fromIdx, toIdx, startNumber)
  if (!selected.length) return ''
  const from = selected[0]
  const to = selected[selected.length - 1]
  const lengthStr = formatLength(calcLength(selected))

  const coordinates = selected.map(t => `${t.lon},${t.lat},0`).join('\n\t\t\t\t')

  const placemarks = selected
    .map((t) => {
      const label = (t.name || '').trim()
      // Google Earth shows the placemark name, so the label belongs there — but
      // after the number, which is what numberFromName reads back on re-import.
      const title = `Tower ${xml(t.towerNumber)}${label ? ` — ${xml(label)}` : ''}`
      const extended = [
        t.osmId ? `<Data name="osmId"><value>${xml(t.osmId)}</value></Data>` : '',
        label ? `<Data name="label"><value>${xml(label)}</value></Data>` : '',
      ].filter(Boolean)

      return `
\t<Placemark>
\t\t<name>${title}</name>
\t\t<description><![CDATA[
\t\t\t<b>Tower Number:</b> ${t.towerNumber}<br/>${label ? `
\t\t\t<b>Label:</b> ${label}<br/>` : ''}${t.osmId ? `
\t\t\t<b>OSM Node ID:</b> ${t.osmId}<br/>` : ''}
\t\t\t<b>Latitude:</b> ${t.lat.toFixed(7)}<br/>
\t\t\t<b>Longitude:</b> ${t.lon.toFixed(7)}
\t\t]]></description>
\t\t<styleUrl>#towerStyle</styleUrl>${extended.length ? `
\t\t<ExtendedData>${extended.join('')}</ExtendedData>` : ''}
\t\t<Point>
\t\t\t<coordinates>${t.lon},${t.lat},0</coordinates>
\t\t</Point>
\t</Placemark>`
    })
    .join('\n')

  return `<?xml version="1.0" encoding="UTF-8"?>
<kml xmlns="http://www.opengis.net/kml/2.2">
<Document>
\t<name>${xml(lineName)} — Tower ${xml(from.towerNumber)} to Tower ${xml(to.towerNumber)}</name>
\t<description>Generated by सर्जनम् | ${selected.length} towers | Length: ${lengthStr} | ${xml(lineName)}</description>

\t<Style id="lineStyle">
\t\t<LineStyle>
\t\t\t<color>ffee8800</color>
\t\t\t<width>4</width>
\t\t</LineStyle>
\t</Style>

\t<Style id="towerStyle">
\t\t<IconStyle>
\t\t\t<color>ff0000ff</color>
\t\t\t<scale>0.9</scale>
\t\t\t<Icon>
\t\t\t\t<href>http://maps.google.com/mapfiles/kml/shapes/placemark_circle.png</href>
\t\t\t</Icon>
\t\t</IconStyle>
\t\t<LabelStyle>
\t\t\t<scale>0.7</scale>
\t\t</LabelStyle>
\t</Style>

\t<Placemark>
\t\t<name>${xml(lineName)} (${lengthStr})</name>
\t\t<styleUrl>#lineStyle</styleUrl>
\t\t<LineString>
\t\t\t<tessellate>1</tessellate>
\t\t\t<coordinates>
\t\t\t\t${coordinates}
\t\t\t</coordinates>
\t\t</LineString>
\t</Placemark>
${placemarks}
</Document>
</kml>`
}

export function generateCSV(towers, fromIdx, toIdx, lineName, startNumber = 1) {
  const selected = selectTowers(towers, fromIdx, toIdx, startNumber)

  const esc = (v) => {
    const s = String(v ?? '')
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
  }

  const header = ['Tower Number', 'Label', 'OSM Node ID', 'Latitude', 'Longitude', 'Line Name']
  const rows = selected.map((t) => [
    t.towerNumber,
    (t.name || '').trim(),
    t.osmId ?? '', // blank for towers that came from a KML rather than OSM
    t.lat.toFixed(7),
    t.lon.toFixed(7),
    lineName,
  ])

  return [header, ...rows].map((r) => r.map(esc).join(',')).join('\r\n')
}

function download(content, filename, mime) {
  const blob = new Blob([content], { type: mime })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}

export function downloadKML(content, filename) {
  download(content, filename, 'application/vnd.google-earth.kml+xml')
}

export function downloadCSV(content, filename) {
  download(content, filename, 'text/csv;charset=utf-8')
}
