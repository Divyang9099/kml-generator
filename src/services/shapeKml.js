import {
  createShape, outlineOf, measurementOf, PALETTE,
  areaOf, lengthOf, isBadRing, TYPE_LABEL,
} from './shapes.js'
import { SQM_PER_ACRE } from './geo.js'

const xml = (v) =>
  String(v ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')

// KML colours are aabbggrr — alpha first, and the RGB bytes reversed.
export function toKmlColor(hex, opacity = 1) {
  const m = /^#?([0-9a-f]{6})$/i.exec(String(hex || ''))
  const rgb = m ? m[1] : '000000'
  const a = Math.round(Math.max(0, Math.min(1, opacity)) * 255)
    .toString(16).padStart(2, '0')
  return `${a}${rgb.slice(4, 6)}${rgb.slice(2, 4)}${rgb.slice(0, 2)}`.toLowerCase()
}

export function fromKmlColor(kml) {
  const m = /^([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(String(kml || '').trim())
  if (!m) return null
  const [, a, b, g, r] = m
  return { hex: `#${r}${g}${b}`.toLowerCase(), opacity: parseInt(a, 16) / 255 }
}

const ICON_HREF = {
  pin: 'http://maps.google.com/mapfiles/kml/pushpin/ylw-pushpin.png',
  circle: 'http://maps.google.com/mapfiles/kml/shapes/placemark_circle.png',
  square: 'http://maps.google.com/mapfiles/kml/shapes/placemark_square.png',
  star: 'http://maps.google.com/mapfiles/kml/shapes/star.png',
  triangle: 'http://maps.google.com/mapfiles/kml/shapes/triangle.png',
}

const coordString = (coords) => coords.map(([lat, lon]) => `${lon},${lat},0`).join(' ')

function geometryFor(shape) {
  if (shape.type === 'point') {
    const [lat, lon] = shape.coords[0]
    return `<Point><coordinates>${lon},${lat},0</coordinates></Point>`
  }
  if (shape.type === 'line') {
    return `<LineString><tessellate>1</tessellate><coordinates>${coordString(shape.coords)}</coordinates></LineString>`
  }
  // KML has no rectangle or circle — both go out as closed polygons, which is
  // what every reader expects and what Google Earth draws.
  const ring = (r) => `<LinearRing><coordinates>${coordString([...r, r[0]])}</coordinates></LinearRing>`
  const holes = shape.type === 'polygon' ? shape.holes ?? [] : []
  const inner = holes.map((h) => `<innerBoundaryIs>${ring(h)}</innerBoundaryIs>`).join('')
  return `<Polygon><tessellate>1</tessellate><outerBoundaryIs>${ring(outlineOf(shape))}</outerBoundaryIs>${inner}</Polygon>`
}

function styleFor(shape) {
  const line = `<LineStyle><color>${toKmlColor(shape.color, 1)}</color><width>${shape.width ?? 3}</width></LineStyle>`
  if (shape.type === 'point') {
    return `<IconStyle><color>${toKmlColor(shape.color, 1)}</color><scale>${shape.iconScale ?? 1}</scale><Icon><href>${ICON_HREF[shape.icon] || ICON_HREF.pin}</href></Icon></IconStyle>`
  }
  if (shape.type === 'line') return line
  return `${line}<PolyStyle><color>${toKmlColor(shape.color, shape.opacity ?? 0.25)}</color><fill>1</fill><outline>1</outline></PolyStyle>`
}

export function generateShapeKML(shapes, docName = 'Custom KML') {
  const styles = shapes
    .map((s) => `\t<Style id="style-${s.id}">${styleFor(s)}</Style>`)
    .join('\n')

  const placemarks = shapes
    .map((s, i) => {
      const name = s.name?.trim() || `${s.type} ${i + 1}`
      const notes = s.description?.trim()
      return `
\t<Placemark>
\t\t<name>${xml(name)}</name>
\t\t<description><![CDATA[${notes ? `${notes}<br/>` : ''}<b>${s.type}</b> — ${measurementOf(s)}]]></description>
\t\t<styleUrl>#style-${s.id}</styleUrl>
\t\t<ExtendedData><Data name="shapeType"><value>${s.type}</value></Data>${
        s.type === 'circle' ? `<Data name="radius"><value>${s.radius}</value></Data>` : ''
      }</ExtendedData>
\t\t${geometryFor(s)}
\t</Placemark>`
    })
    .join('\n')

  return `<?xml version="1.0" encoding="UTF-8"?>
<kml xmlns="http://www.opengis.net/kml/2.2">
<Document>
\t<name>${xml(docName)}</name>
\t<description>Generated by सर्जनम् | ${shapes.length} features</description>
${styles}
${placemarks}
</Document>
</kml>`
}

/* ── Reading shapes back ─────────────────────────────────────────────── */

const all = (node, tag) => Array.from(node.getElementsByTagNameNS('*', tag))
const first = (node, tag) => node.getElementsByTagNameNS('*', tag)[0] || null

function childText(parent, tag) {
  for (const child of parent.children) {
    if (child.localName === tag) return child.textContent.trim()
  }
  return ''
}

function parseCoords(text) {
  return text
    .trim()
    .split(/\s+/)
    .map((t) => {
      const [lon, lat] = t.split(',').map(Number)
      if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null
      if (lat < -90 || lat > 90 || lon < -180 || lon > 180) return null
      return [lat, lon]
    })
    .filter(Boolean)
}

function extendedValue(placemark, key) {
  for (const data of all(placemark, 'Data')) {
    if (data.getAttribute('name') !== key) continue
    const v = first(data, 'value')
    if (v) return v.textContent.trim()
  }
  return undefined
}

// Style lookup: a placemark may point at a shared <Style>, at a <StyleMap>
// that points at one, or carry its own inline style.
function buildStyleIndex(doc) {
  const index = {}
  for (const style of all(doc, 'Style')) {
    const id = style.getAttribute('id')
    if (id) index[`#${id}`] = style
  }
  for (const map of all(doc, 'StyleMap')) {
    const id = map.getAttribute('id')
    if (!id) continue
    const normal = all(map, 'Pair').find((p) => childText(p, 'key') === 'normal')
    const url = normal ? childText(normal, 'styleUrl') : ''
    if (url && index[url]) index[`#${id}`] = index[url]
  }
  return index
}

function readStyle(placemark, index) {
  const url = childText(placemark, 'styleUrl')
  const style = (url && index[url]) || first(placemark, 'Style')
  if (!style) return {}

  const out = {}
  const lineColor = first(style, 'LineStyle') && childText(first(style, 'LineStyle'), 'color')
  const iconColor = first(style, 'IconStyle') && childText(first(style, 'IconStyle'), 'color')
  const parsed = fromKmlColor(lineColor || iconColor)
  if (parsed) out.color = parsed.hex

  const width = first(style, 'LineStyle') && childText(first(style, 'LineStyle'), 'width')
  if (width) out.width = Number(width) || 3

  const poly = first(style, 'PolyStyle')
  const polyParsed = poly && fromKmlColor(childText(poly, 'color'))
  if (polyParsed) out.opacity = polyParsed.opacity

  const scale = first(style, 'IconStyle') && childText(first(style, 'IconStyle'), 'scale')
  if (scale) out.iconScale = Number(scale) || 1

  return out
}

export function parseShapeKML(text, fallbackName = 'Imported') {
  if (!text || !text.trim()) throw new Error('That file is empty.')

  const doc = new DOMParser().parseFromString(text, 'application/xml')
  if (first(doc, 'parsererror')) {
    throw new Error('This file is not valid XML — is it really a KML?')
  }

  const styleIndex = buildStyleIndex(doc)
  const shapes = []

  for (const placemark of all(doc, 'Placemark')) {
    const name = childText(placemark, 'name')
    const description = childText(placemark, 'description')
    const style = readStyle(placemark, styleIndex)
    // Our own export records what a polygon really was, so a circle comes back
    // as a circle rather than as its 72-sided approximation.
    const declared = extendedValue(placemark, 'shapeType')
    const radius = Number(extendedValue(placemark, 'radius'))

    const push = (type, coords, extra = {}) => {
      if (!coords.length) return
      shapes.push(createShape(type, coords, {
        name,
        description,
        color: style.color || PALETTE[shapes.length % PALETTE.length],
        width: style.width ?? 3,
        opacity: style.opacity ?? 0.25,
        iconScale: style.iconScale ?? 1,
        ...extra,
      }))
    }

    for (const point of all(placemark, 'Point')) {
      const c = first(point, 'coordinates')
      if (c) push('point', parseCoords(c.textContent).slice(0, 1))
    }

    for (const line of all(placemark, 'LineString')) {
      const c = first(line, 'coordinates')
      if (c) push('line', parseCoords(c.textContent))
    }

    for (const polygon of all(placemark, 'Polygon')) {
      const outer = first(polygon, 'outerBoundaryIs') || polygon
      const coords = readRing(first(outer, 'LinearRing'))
      if (!coords) continue
      if (declared === 'circle' && Number.isFinite(radius) && radius > 0) {
        const centre = centroid(coords)
        push('circle', [centre], { radius })
      } else if (declared === 'rectangle' && coords.length >= 4) {
        const lats = coords.map((p) => p[0])
        const lons = coords.map((p) => p[1])
        push('rectangle', [[Math.max(...lats), Math.min(...lons)], [Math.min(...lats), Math.max(...lons)]])
      } else {
        const holes = all(polygon, 'innerBoundaryIs')
          .map((b) => readRing(first(b, 'LinearRing')))
          .filter((h) => h && h.length >= 3)
        push('polygon', coords, holes.length ? { holes } : {})
      }
    }
  }

  if (!shapes.length) {
    throw new Error('No points, paths or polygons found in this file.')
  }

  const documentEl = first(doc, 'Document')
  const docName = (documentEl && childText(documentEl, 'name')) || fallbackName
  return { name: docName, shapes }
}

// Rings repeat their first point to close; the editor does not.
function readRing(ring) {
  const c = ring && first(ring, 'coordinates')
  if (!c) return null
  const coords = parseCoords(c.textContent)
  if (coords.length > 1) {
    const [a, b] = [coords[0], coords[coords.length - 1]]
    if (a[0] === b[0] && a[1] === b[1]) return coords.slice(0, -1)
  }
  return coords
}

function centroid(coords) {
  const lat = coords.reduce((s, p) => s + p[0], 0) / coords.length
  const lon = coords.reduce((s, p) => s + p[1], 0) / coords.length
  return [lat, lon]
}

// WKT is "lon lat", and a ring is written closed.
const wktPoint = ([lat, lon]) => `${+lon.toFixed(7)} ${+lat.toFixed(7)}`
const wktRing = (ring) => `(${[...ring, ring[0]].map(wktPoint).join(', ')})`

// The shape's real geometry, so the CSV is not just a list of centres: it opens
// in QGIS / Excel-with-GIS, and this app reads it straight back as the same
// points, lines and polygons (holes included). A circle goes out as its outline.
function wktOf(shape) {
  if (shape.type === 'point') return `POINT (${wktPoint(shape.coords[0])})`
  if (shape.type === 'line') return `LINESTRING (${shape.coords.map(wktPoint).join(', ')})`
  const holes = shape.type === 'polygon' ? shape.holes ?? [] : []
  return `POLYGON (${[outlineOf(shape), ...holes].map(wktRing).join(', ')})`
}

// A spreadsheet of what was drawn — the Draw workspace's counterpart to the
// tower CSV, so shapes can be handed to someone who does not open KML.
export function generateShapeCSV(shapes) {
  const esc = (v) => {
    const s = String(v ?? '')
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
  }

  const header = [
    'ID', 'Name', 'Type', 'Points', 'Length (m)', 'Area (acres)', 'Radius (m)',
    'Centre Latitude', 'Centre Longitude', 'Colour', 'Description', 'WKT',
  ]

  const rows = shapes.map((s, i) => {
    // Points and lines have no outline; their own coordinates are the shape.
    const pts = s.type === 'circle' ? s.coords : outlineOf(s) ?? s.coords
    const centre = pts.reduce(
      (acc, [lat, lon]) => [acc[0] + lat / pts.length, acc[1] + lon / pts.length],
      [0, 0]
    )
    const area = s.type === 'line' || s.type === 'point' || isBadRing(s) ? '' : areaOf(s) / SQM_PER_ACRE
    return [
      s.id ?? `s${i + 1}`,
      s.name?.trim() || TYPE_LABEL[s.type],
      s.type,
      s.type === 'circle' ? '' : s.coords.length,
      s.type === 'point' ? '' : Math.round(lengthOf(s)),
      area === '' ? '' : area.toFixed(3),
      s.type === 'circle' ? Math.round(s.radius) : '',
      centre[0].toFixed(7),
      centre[1].toFixed(7),
      s.color,
      s.description ?? '',
      wktOf(s),
    ]
  })

  return [header, ...rows].map((r) => r.map(esc).join(',')).join('\r\n')
}
